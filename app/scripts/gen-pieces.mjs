// Extracts the cburnett piece SVGs (CC BY-SA 3.0, Colin M.L. Burnett) that ship with
// chessground into a TS module, so mini-boards and figurines use the same artwork as the
// main board. Run once: node scripts/gen-pieces.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync("node_modules/chessground/assets/chessground.cburnett.css", "utf8");
const re = /piece\.(\w+)\.(white|black)\s*\{\s*background-image:\s*url\('([^']+)'\)/g;
const letter = { pawn: "P", knight: "N", bishop: "B", rook: "R", queen: "Q", king: "K" };
const out = {};
for (const m of css.matchAll(re)) out[(m[2] === "white" ? "w" : "b") + letter[m[1]]] = m[3];
const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n");
writeFileSync(
  "src/board/pieces.ts",
  `// Generated by scripts/gen-pieces.mjs from chessground's cburnett set (CC BY-SA 3.0).\n` +
    `export const PIECE_SVG: Record<string, string> = {\n${body}\n};\n`,
);
console.log("pieces:", Object.keys(out).join(" "));
